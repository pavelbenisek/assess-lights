"""Step 3/8: frame quality metrics via PixInsight's SubframeSelector, headless.

The PJSR source below is deliberately written for the **V8** runtime
(`#engine v8`).  Without that directive PixInsight falls back to the legacy
SpiderMonkey runtime, where core objects such as `Runtime` are undefined and
the script dies.  Three other V8-era facts are baked in here, all verified
against PixInsight 1.9.5 on macOS:

  * PJSR console output does NOT reach the process stdout, so the script
    reports results by writing files (and the caller must not rely on stdout);
  * `File.searchDirectory` needs a wildcard spec ("dir/*"), a bare directory
    silently yields zero entries;
  * table parameters such as `SubframeSelector.subframes` require 4-column
    rows `[enabled, filePath, drizzlePath, localNormalizationPath]`
    (see PixInsight's own BPP-Helper.js).
"""

from __future__ import annotations

import csv
import json
import os
import shutil
import subprocess
import tempfile
import time
from dataclasses import dataclass
from pathlib import Path

from .config import DEFAULT_PI_BINARY

PJSR_TEMPLATE = r'''#engine v8

// Generated by assess-lights. Measures frames with SubframeSelector and writes CSV.
var JOB = __JOB_JSON__;

function W( s ) { log.push( String( s ) ); File.writeTextFile( job.log, log.join( "\n" ) + "\n" ); }

var log = [];
var job;
try { job = JSON.parse( File.readTextFile( JOB ) ); }
catch ( e ) { File.writeTextFile( "/tmp/assess_lights_pi_error.txt", "cannot read job file: " + e ); }

W( "start " + (new Date()).toString() );

var rows = [ "file,FWHM,eccentricity,stars,SNR,noise,MAD,Mstar,PSFSNR,PSFSignalWeight" ];
File.writeTextFile( job.csv, rows.join( "\n" ) + "\n" );

var frames = job.frames;
W( "frames to measure: " + frames.length );

var B = job.batch;
for ( var b = 0; b < frames.length; b += B )
{
   var subset = frames.slice( b, b + B );
   W( "batch @" + b + " n=" + subset.length + " " + (new Date()).toString() );

   var M = new SubframeSelector;
   M.routine          = SubframeSelector.MeasureSubframes;
   M.nonInteractive   = true;
   M.cameraResolution = SubframeSelector.Bits16;
   M.scaleUnit        = SubframeSelector.ArcSeconds;
   M.dataUnit         = SubframeSelector.DataNumber;
   M.fileCache        = false;
   M.noNoiseAndSignalWarnings = true;

   var target = new Array;
   for ( var i = 0; i < subset.length; ++i )
      target.push( [ true, subset[i], "", "" ] );
   M.subframes = target;

   var ok = false;
   try { ok = M.executeGlobal(); }
   catch ( e ) { W( "  executeGlobal THREW: " + e ); continue; }

   W( "  ok=" + ok + " rows=" + M.measurements.length );
   if ( !ok ) continue;

   for ( var i = 0; i < M.measurements.length; ++i )
   {
      var r = M.measurements[i];
      rows.push( String(r[3]) + "," + r[5] + "," + r[6] + "," + r[14]
               + "," + r[9] + "," + r[12] + "," + r[11] + "," + r[26] + "," + r[28] + "," + r[7] );
   }
   File.writeTextFile( job.csv, rows.join( "\n" ) + "\n" );
}

W( "DONE " + (new Date()).toString() );
'''


@dataclass
class PiMetrics:
    path: Path
    FWHM: float
    eccentricity: float
    stars: int
    SNR: float
    noise: float
    MAD: float
    Mstar: float
    PSFSNR: float
    PSFSignalWeight: float


class PixInsightError(RuntimeError):
    pass


def resolve_pi_binary(explicit: str | None = None) -> Path:
    cand = explicit or os.environ.get("ASSESS_LIGHTS_PI_BINARY") or DEFAULT_PI_BINARY
    p = Path(cand)
    if not p.exists():
        raise PixInsightError(
            f"PixInsight binary not found at {p}. "
            "Pass --pi-binary or set ASSESS_LIGHTS_PI_BINARY."
        )
    return p


def measure(
    frames: list[Path],
    pi_binary: Path,
    batch: int = 10,
    timeout: int = 3600,
    workdir: Path | None = None,
    progress=None,
    tick=None,
) -> dict[Path, PiMetrics]:
    """Run SubframeSelector headless over `frames`; return metrics keyed by path.

    `tick(completed)` is called while PixInsight runs, with the number of frames
    written to the results CSV so far, so callers can drive a progress bar.
    """
    work = Path(workdir) if workdir else Path(tempfile.mkdtemp(prefix="assess-lights-pi-"))
    work.mkdir(parents=True, exist_ok=True)
    script = work / "measure.js"
    job_path = work / "job.json"
    csv_path = work / "metrics.csv"
    log_path = work / "pi.log"

    job = {
        "frames": [str(p) for p in frames],
        "csv": str(csv_path),
        "log": str(log_path),
        "batch": int(batch),
    }
    job_path.write_text(json.dumps(job), encoding="utf-8")
    script.write_text(
        PJSR_TEMPLATE.replace("__JOB_JSON__", json.dumps(str(job_path))),
        encoding="utf-8",
    )

    cmd = [
        str(pi_binary),
        "-n",
        "--automation-mode",
        "--no-startup-scripts",
        f"-r={script}",
        "--force-exit",
    ]
    if progress:
        progress(f"launching SubframeSelector on {len(frames)} frame(s)")

    # stdout/stderr go to files rather than PIPE: the process is polled while it
    # runs, and an unread pipe would fill up and deadlock it.
    out_path = work / "pi.stdout"
    err_path = work / "pi.stderr"

    with out_path.open("w") as out_f, err_path.open("w") as err_f:
        proc = subprocess.Popen(cmd, stdout=out_f, stderr=err_f, text=True)
        deadline = time.time() + timeout
        seen = 0
        while proc.poll() is None:
            if time.time() > deadline:
                proc.kill()
                proc.wait()
                raise PixInsightError(f"PixInsight timed out after {timeout}s")
            if tick is not None:
                n = _csv_rows(csv_path)
                if n > seen:
                    seen = n
                    tick(min(n, len(frames)))
            time.sleep(0.4)

    stdout = out_path.read_text(encoding="utf-8", errors="replace")
    stderr = err_path.read_text(encoding="utf-8", errors="replace")

    if not csv_path.exists():
        detail = log_path.read_text(encoding="utf-8", errors="replace") if log_path.exists() else "(no PJSR log)"
        raise PixInsightError(
            "PixInsight produced no metrics.csv.\n"
            f"exit={proc.returncode}\n--- PJSR log ---\n{detail}\n"
            "--- stdout ---\n" + stdout[-2000:]
            + ("\n--- stderr ---\n" + stderr[-1000:] if stderr.strip() else "")
        )

    if tick is not None:
        tick(len(frames))

    return _parse_metrics(csv_path)


def _csv_rows(csv_path: Path) -> int:
    """Data rows currently in the results CSV (0 while it is being rewritten)."""
    try:
        with csv_path.open(encoding="utf-8") as fh:
            return max(0, sum(1 for _ in fh) - 1)
    except Exception:  # noqa: BLE001  (file may be mid-write)
        return 0


def _parse_metrics(csv_path: Path) -> dict[Path, PiMetrics]:
    out: dict[Path, PiMetrics] = {}
    with csv_path.open(newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            name = (row.get("file") or "").strip()
            if not name:
                continue
            try:
                m = PiMetrics(
                    path=Path(name),
                    FWHM=float(row["FWHM"]),
                    eccentricity=float(row["eccentricity"]),
                    stars=int(float(row["stars"])),
                    SNR=float(row["SNR"]),
                    noise=float(row["noise"]),
                    MAD=float(row.get("MAD") or 0.0),
                    Mstar=float(row.get("Mstar") or 0.0),
                    PSFSNR=float(row.get("PSFSNR") or 0.0),
                    PSFSignalWeight=float(row.get("PSFSignalWeight") or 0.0),
                )
            except (TypeError, ValueError):
                continue
            out[m.path] = m
    return out
